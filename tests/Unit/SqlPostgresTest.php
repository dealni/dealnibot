<?php

declare(strict_types=1);

namespace Tests;

use PHPUnit\Framework\TestCase;
use SqlPostgres;

require_once __DIR__ . '/../../inclusos/SqlPostgres.php';

final class SqlPostgresTest extends TestCase
{
    public function testIdempotenciaUsaConflitoSemAlterarPayloadLiteral(): void
    {
        $sql = "INSERT OR IGNORE INTO inbox (payload) VALUES ('INSERT OR IGNORE `float`');";
        $this->assertSame("INSERT INTO inbox (payload) VALUES ('INSERT OR IGNORE `float`') ON CONFLICT DO NOTHING", SqlPostgres::converter($sql));
    }

    public function testSchemaPreservaIdsEPrecisao(): void
    {
        $sql = 'CREATE TABLE t (`id` INTEGER PRIMARY KEY AUTOINCREMENT, update_id BIGINT PRIMARY KEY, valor REAL, nome VARCHAR(100), ativo BOOLEAN DEFAULT 0)';
        $resultado = SqlPostgres::converter($sql);
        $this->assertStringContainsString('"id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', $resultado);
        $this->assertStringContainsString('update_id BIGINT PRIMARY KEY', $resultado);
        $this->assertStringContainsString('DOUBLE PRECISION', $resultado);
        $this->assertStringContainsString('nome TEXT', $resultado);
        $this->assertStringNotContainsString('BIGINT EGER', $resultado);
    }

    public function testAgregadoMaxContinuaAgregado(): void
    {
        $this->assertSame('SELECT MAX(id), GREATEST(0, saldo - ?) FROM usuarios', SqlPostgres::converter('SELECT MAX(id), MAX(0, saldo - ?) FROM usuarios'));
    }

    public function testArredondamentoFinanceiroUsaNumeric(): void
    {
        $this->assertSame('UPDATE usuarios SET saldo = ROUND(CAST(saldo + ? AS NUMERIC), 2)', SqlPostgres::converter('UPDATE usuarios SET saldo = ROUND(saldo + ?, 2)'));
    }

    public function testAspasDuplicadasEComentariosNaoSaoReescritos(): void
    {
        $sql = "SELECT 'O''Brien MAX(0, 1) `id`' -- INTEGER PRIMARY KEY\n";
        $this->assertSame($sql, SqlPostgres::converter($sql));
    }

    public function testFormatoDeDataDesconhecidoFalhaExplicitamente(): void
    {
        $this->expectException(\RuntimeException::class);
        SqlPostgres::converter("SELECT datetime(data, 'unixepoch', 'localtime')");
    }
    public function testBuscaMantemComparacaoSemDistinguirCaixa(): void
    {
        $this->assertSame("SELECT * FROM canais WHERE nome_canal ILIKE ? AND area NOT ILIKE 'LIKE'", SqlPostgres::converter("SELECT * FROM canais WHERE nome_canal LIKE ? AND area NOT LIKE 'LIKE'"));
    }


    public function testJsonPreservaLiteraisEAdaptaSomenteOsCamposDaFila(): void
    {
        $sql = "SELECT json_extract(f.payload, '$.id_sms') FROM fila f WHERE json_valid(f.payload) AND observacao = 'json_valid(payload)'";
        $this->assertSame("SELECT json_extract_path_text(CAST(f.payload AS JSON), 'id_sms') FROM fila f WHERE (f.payload IS JSON) AND observacao = 'json_valid(payload)'", SqlPostgres::converter($sql));
    }

    public function testCaminhoJsonForaDoContratoEhRecusado(): void
    {
        $this->expectException(\RuntimeException::class);
        SqlPostgres::converter("SELECT json_extract(payload, '$.outro') FROM fila");
    }
}
