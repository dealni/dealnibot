<?php

declare(strict_types=1);

// --- DADOS DESTE REPOSITÓRIO (a personalização entra só neste bloco) --------
/**
 * Token que scripts/deploy/db_restore.php exige em DB_RESTORE_CONFIRM antes de
 * escrever num banco: o nome deste bot, digitado por inteiro.
 *
 * @var string
 */
$confirmacaoDeRestauracao = 'dealnibot';
// --- FIM DOS DADOS; daqui para baixo o código é canônico --------------------

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit(1);
}
require_once dirname(__DIR__, 2) . '/tests/Support/ExecutorCli.php';
if (getenv('CHATBOTS_PG_TEST_DSN') === false || getenv('CHATBOTS_PG_TEST_DSN') === '') {
    passthru(implode(' ', array_map(escapeshellarg(...), ['bash', __DIR__ . '/with_postgres.sh', ...\Tests\Support\ExecutorCli::comando(__FILE__)])), $statusPostgres);
    exit($statusPostgres);
}
putenv('APP_ENV=test');
putenv('CHATBOTS_TESTING=1');
require dirname(__DIR__, 2) . '/tests/Support/BancoTeste.php';
require dirname(__DIR__, 2) . '/inclusos/funcoes_snapshot_banco.php';
$dsn = getenv('CHATBOTS_PG_TEST_DSN');
if (!is_string($dsn)) {
    throw new RuntimeException('DSN de teste ausente.');
}
$pdo = BancoTeste::conectar(BancoTeste::dsn($dsn));
$nome = ConsultaBanco::coluna($pdo, 'SELECT current_database()');
if (!is_string($nome) || !str_starts_with($nome, 'chatbots_test_')) {
    throw new RuntimeException('Restauração sintética exige banco descartável.');
}
if ((int) ConsultaBanco::coluna($pdo, "SELECT count(*) FROM pg_tables WHERE schemaname NOT IN ('pg_catalog', 'information_schema')") !== 0) {
    throw new RuntimeException('Restauração sintética exige banco vazio.');
}
$pdo->exec('CREATE TABLE public.prova_restauracao (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, valor TEXT NOT NULL)');
$pdo->exec("INSERT INTO public.prova_restauracao (valor) VALUES ('ação 🚀')");
$dir = sys_get_temp_dir() . '/pg-restore-' . bin2hex(random_bytes(8));
mkdir($dir, 0700);
try {
    $resultado = executarSnapshotBanco($dsn, $dir, 1);
    if (!snapshotBancoIntegro($resultado['arquivo'])) {
        throw new RuntimeException('Dump ou metadados inválidos.');
    }
    // O schema public já existe, como num banco novo criado para produção.
    $pdo->exec('DROP TABLE public.prova_restauracao');
    $ambiente = getenv();
    $ambiente['TEST_DATABASE_DSN'] = $dsn;
    $ambiente['DB_RESTORE_CONFIRM'] = $confirmacaoDeRestauracao;
    $processo = proc_open(\Tests\Support\ExecutorCli::comando(dirname(__DIR__) . '/deploy/db_restore.php', ['--arquivo=' . $resultado['arquivo']]), [1 => ['pipe', 'w'], 2 => ['pipe', 'w']], $pipes, null, $ambiente);
    if (!is_resource($processo)) {
        throw new RuntimeException('Não foi possível iniciar a restauração sintética.');
    }
    $saida = stream_get_contents($pipes[1]) . stream_get_contents($pipes[2]);
    fclose($pipes[1]);
    fclose($pipes[2]);
    if (proc_close($processo) !== 0) {
        throw new RuntimeException('Restauração sintética falhou: ' . $saida);
    }
    if (ConsultaBanco::coluna($pdo, 'SELECT valor FROM public.prova_restauracao WHERE id = 1') !== 'ação 🚀') {
        throw new RuntimeException('Restauração perdeu os dados sintéticos.');
    }
    if (ConsultaBanco::coluna($pdo, "INSERT INTO public.prova_restauracao (valor) VALUES ('sequência') RETURNING id") !== 2) {
        throw new RuntimeException('Restauração perdeu a sequência de IDs.');
    }
    require_once dirname(__DIR__, 2) . '/src/Support/ReciboRecuperacao.php';
    $hash = hash_file('sha256', $resultado['arquivo']);
    if (!is_string($hash)) {
        throw new RuntimeException('Não foi possível calcular o hash do conjunto restaurado.');
    }
    $recibo = \App\Support\ReciboRecuperacao::sintetico($resultado['arquivo'], $hash, $nome);
    $evidencias = dirname(__DIR__, 2) . '/.artifacts/backup';
    if (!is_dir($evidencias) && !mkdir($evidencias, 0700, true)) {
        throw new RuntimeException('Não foi possível criar diretório privado de evidências.');
    }
    if (is_link($evidencias)) {
        throw new RuntimeException('Diretório de evidências não pode ser symlink.');
    }
    if (!chmod($evidencias, 0700)) {
        throw new RuntimeException('Não foi possível proteger diretório de evidências.');
    }
    $arquivoEvidencia = $evidencias . '/restore-sintetico-' . gmdate('Ymd\THis\Z') . '-' . bin2hex(random_bytes(4)) . '.json';
    $json = json_encode(['executadoEm' => gmdate('c'), ...$recibo], JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR) . "\n";
    $anterior = umask(0077);
    try {
        if (file_put_contents($arquivoEvidencia, $json, LOCK_EX) !== strlen($json)) {
            throw new RuntimeException('Não foi possível gravar evidência da restauração.');
        }
    } finally {
        umask($anterior);
    }
    echo "Dump e restauração PostgreSQL: OK (dados sintéticos).\n";
    echo "Recibo sintético: {$arquivoEvidencia}; backup de produção não restaurado.\n";
} finally {
    foreach (ConsultaBanco::arquivos($dir . '/*') as $arquivo) {
        unlink($arquivo);
    }
    rmdir($dir);
    $pdo->exec('DROP TABLE IF EXISTS public.prova_restauracao');
}
