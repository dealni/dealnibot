<?php

declare(strict_types=1);

/** Adapta somente as construções SQL presentes nos bots; dados continuam em binds. */
final class SqlPostgres
{
    public static function converter(string $sql): string
    {
        // Protege literais e comentários: palavras SQL dentro de dados nunca
        // devem ser alteradas. Marcadores são locais e não entram no banco.
        $literais = [];
        $codigo = preg_replace_callback(
            "~'(?:''|[^'])*'|--[^\r\n]*|/\*.*?\*/~s",
            static function (array $m) use (&$literais): string {
                $chave = "\x01" . count($literais) . "\x02";
                $literais[$chave] = $m[0];
                return $chave;
            },
            $sql
        );
        if ($codigo === null) {
            throw new RuntimeException('SQL inválido.');
        }
        $codigo = self::converterJson($codigo, $literais);
        $codigo = str_replace('`', '"', $codigo);
        // LIKE legado é insensível a caixa (buscas e filtros de códigos).
        $codigo = (string) preg_replace('/\bLIKE\b/i', 'ILIKE', $codigo);
        $ignorar = preg_match('/^\s*INSERT\s+OR\s+IGNORE\s+/i', $codigo) === 1;
        $codigo = (string) preg_replace('/^\s*INSERT\s+OR\s+IGNORE\s+/i', 'INSERT ', $codigo);
        if ($ignorar) {
            $codigo = rtrim($codigo, " \r\n\t;") . ' ON CONFLICT DO NOTHING';
        }
        $codigo = (string) preg_replace('/\bMAX\s*\(\s*0\s*,/i', 'GREATEST(0,', $codigo);
        // round(double precision, integer) não existe no PostgreSQL.
        $codigo = (string) preg_replace('/\bROUND\(([^(),]+),\s*(\d+)\)/i', 'ROUND(CAST($1 AS NUMERIC), $2)', $codigo);
        // Relatórios existentes trabalham com epoch e deslocamento fixo -03.
        $codigo = (string) preg_replace_callback(
            '/\bdatetime\(\s*([\w.]+)\s*,\s*(\x01\d+\x02)\s*,\s*(\x01\d+\x02)\s*\)/i',
            static function (array $m) use ($literais): string {
                if (($literais[$m[2]] ?? '') !== "'unixepoch'" || ($literais[$m[3]] ?? '') !== "'-3 hours'") {
                    throw new RuntimeException('Formato datetime não suportado no PostgreSQL.');
                }
                return "(to_timestamp(CAST({$m[1]} AS DOUBLE PRECISION)) AT TIME ZONE 'UTC' - INTERVAL '3 hours')";
            },
            $codigo
        );
        $codigo = (string) preg_replace_callback(
            '/\bstrftime\(\s*(\x01\d+\x02)\s*,/i',
            static function (array $m) use ($literais): string {
                if (($literais[$m[1]] ?? '') !== "'%H'") {
                    throw new RuntimeException('Formato strftime não suportado no PostgreSQL.');
                }
                return 'chatbots_hora(';
            },
            $codigo
        );
        if (preg_match('/\bCREATE\s+TABLE\b/i', $codigo) === 1) {
            // SQLite não limita VARCHAR(n) e usa inteiros de 64 bits. TEXT e
            // BIGINT preservam esses contratos e os IDs grandes do Telegram.
            $codigo = (string) preg_replace('/\bBOOLEAN\b/i', 'BIGINT', $codigo);
            $codigo = (string) preg_replace('/\b(?:varchar|char)\s*\(\d+\)/i', 'TEXT', $codigo);
            $codigo = (string) preg_replace('/\b(?:bigint|tinyint|integer|int)\b\s*(?:\(\d+\))?/i', 'BIGINT ', $codigo);
            $codigo = (string) preg_replace('/\b(?:float|real|double)\b(?!\s+precision)/i', 'DOUBLE PRECISION', $codigo);
            $codigo = (string) preg_replace('/(?<![\w"])("?id"?\s+)BIGINT\s+PRIMARY KEY(?:\s+AUTOINCREMENT)?/i', '$1BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', $codigo);
            $codigo = (string) preg_replace('/\s+AUTOINCREMENT\b/i', '', $codigo);
        }
        return strtr($codigo, $literais);
    }

    /** @param array<string, string> $literais */
    private static function converterJson(string $codigo, array $literais): string
    {
        // Predicado usado pela inbox; JSON malformado retorna falso, sem cast.
        $codigo = (string) preg_replace('/\bjson_valid\(\s*([\w.]+)\s*\)/i', '($1 IS JSON)', $codigo);
        // Os dois campos da fila SMS são strings. Outros caminhos exigem
        // contrato explícito: isto não emula todos os tipos JSON do SQLite.
        return (string) preg_replace_callback(
            '/\bjson_extract\(\s*([\w.]+)\s*,\s*(\x01\d+\x02)\s*\)/i',
            static function (array $m) use ($literais): string {
                $campo = match ($literais[$m[2]] ?? '') {
                    "'$.provedor'" => "'provedor'",
                    "'$.id_sms'" => "'id_sms'",
                    default => throw new RuntimeException('Caminho json_extract não suportado no PostgreSQL.'),
                };
                return "json_extract_path_text(CAST({$m[1]} AS JSON), {$campo})";
            },
            $codigo
        );
    }
}
