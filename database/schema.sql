-- Schema PostgreSQL atual, idempotente. Deploys usam as migrations versionadas em database/postgresql.
CREATE TABLE IF NOT EXISTS broadcast_entregas (
    campanha TEXT NOT NULL,
    id_telegram BIGINT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pendente',
    tentativa_em BIGINT ,
    disponivel_em BIGINT NOT NULL,
    enviado_em BIGINT ,
    tentativas BIGINT NOT NULL DEFAULT 0,
    ultimo_erro TEXT,
    PRIMARY KEY (campanha, id_telegram)
);

CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_telegram BIGINT NOT NULL UNIQUE,
  codigo_idioma TEXT NOT NULL DEFAULT 'pt'
, consentiu_anuncios BIGINT NOT NULL DEFAULT 0
  CHECK (consentiu_anuncios IN (0, 1)), consentido_em TEXT NULL);

CREATE TABLE IF NOT EXISTS webhook_inbox (
    update_id BIGINT PRIMARY KEY,
    payload_json TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pendente',
    recebido_em BIGINT NOT NULL,
    tentativa_em BIGINT ,
    disponivel_em BIGINT NOT NULL,
    processado_em BIGINT ,
    tentativas BIGINT NOT NULL DEFAULT 0,
    ultimo_erro TEXT,
    resposta_ia_json TEXT,
    entrega_ia_estado TEXT CHECK (entrega_ia_estado IN ('enviando', 'pendente', 'entregue', 'indeterminada', 'recusada'))
);

CREATE INDEX IF NOT EXISTS idx_broadcast_entregas_fila
    ON broadcast_entregas (campanha, status, disponivel_em, id_telegram);

CREATE INDEX IF NOT EXISTS idx_webhook_inbox_disponivel
    ON webhook_inbox (status, disponivel_em, update_id);

CREATE OR REPLACE FUNCTION chatbots_hora(timestamp without time zone) RETURNS text LANGUAGE sql IMMUTABLE STRICT AS 'SELECT to_char($1, ''HH24'')';

CREATE INDEX IF NOT EXISTS idx_webhook_inbox_retencao_processados
    ON webhook_inbox (processado_em, update_id) WHERE status = 'processado';
CREATE INDEX IF NOT EXISTS idx_webhook_inbox_retencao_erros
    ON webhook_inbox (recebido_em, update_id) WHERE status = 'erro';

-- Estado de contato independente de contas, saldo e histórico financeiro.
CREATE TABLE IF NOT EXISTS telegram_contatos (
    id_telegram BIGINT PRIMARY KEY CHECK (id_telegram > 0),
    estado TEXT NOT NULL CHECK (estado IN ('disponivel', 'bloqueado', 'desativado', 'nao_encontrado', 'bot')),
    motivo TEXT,
    codigo_erro INTEGER,
    observado_em BIGINT NOT NULL CHECK (observado_em > 0),
    ultima_interacao_em BIGINT NOT NULL DEFAULT 0 CHECK (ultima_interacao_em >= 0)
);
CREATE INDEX IF NOT EXISTS idx_telegram_contatos_indisponiveis
    ON telegram_contatos (id_telegram) WHERE estado <> 'disponivel';
