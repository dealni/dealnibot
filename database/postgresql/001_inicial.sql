-- Baseline PostgreSQL; histórico SQLite preservado em database/migrations.
CREATE TABLE broadcast_entregas (
    campanha TEXT NOT NULL,
    id_telegram BIGINT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pendente',
    tentativa_em BIGINT ,
    disponivel_em BIGINT NOT NULL,
    enviado_em BIGINT ,
    tentativas BIGINT NOT NULL DEFAULT 0,
    ultimo_erro TEXT,
    PRIMARY KEY (campanha, id_telegram)
);

CREATE TABLE usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_telegram BIGINT NOT NULL UNIQUE,
  codigo_idioma TEXT NOT NULL DEFAULT 'pt'
, consentiu_anuncios BIGINT NOT NULL DEFAULT 0
  CHECK (consentiu_anuncios IN (0, 1)), consentido_em TEXT NULL);

CREATE TABLE webhook_inbox (
    update_id BIGINT PRIMARY KEY,
    payload_json TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pendente',
    recebido_em BIGINT NOT NULL,
    tentativa_em BIGINT ,
    disponivel_em BIGINT NOT NULL,
    processado_em BIGINT ,
    tentativas BIGINT NOT NULL DEFAULT 0,
    ultimo_erro TEXT
);

CREATE INDEX idx_broadcast_entregas_fila
    ON broadcast_entregas (campanha, status, disponivel_em, id_telegram);

CREATE INDEX idx_webhook_inbox_disponivel
    ON webhook_inbox (status, disponivel_em, update_id);

CREATE OR REPLACE FUNCTION chatbots_hora(timestamp without time zone) RETURNS text LANGUAGE sql IMMUTABLE STRICT AS 'SELECT to_char($1, ''HH24'')';
